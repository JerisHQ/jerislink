#!/usr/bin/env python3
"""Generate or check the MSIX visual assets from the JerisLink v2.0 icon.

The only input is icon-src/JerisLink-v2.0-1024.png, a byte-for-byte copy of the
approved v2.0 production master (Jeris/Brand/ProductIcons/2.0/JerisLink/
platform/macos/AppIcon.appiconset/icon_512x512@2x.png). Every asset is
downscaled from it; nothing is upscaled. The rounded graphite tile keeps its
transparent corners; Wide310x150 centres the tile on a transparent canvas.

  python gen-assets.py generate   rewrite Assets/*.png and Assets.sources.txt
  python gen-assets.py check      fail unless Assets/ is exactly what generate
                                  would write from the pinned v2.0 master

Needs Pillow (CI pins the version in msix.yml).
"""
import hashlib
import io
import pathlib
import sys

from PIL import Image, ImageChops

HERE = pathlib.Path(__file__).resolve().parent
MASTER = HERE / "icon-src" / "JerisLink-v2.0-1024.png"
# sha256 of the v2.0 master above. Changing the icon means changing this pin.
MASTER_SHA256 = "298bd0ac9981d5c8c502b975d1cc7b5bd198b9cdc7751975bb19be8b6c5635cf"
MASTER_ORIGIN = ("Jeris/Brand/ProductIcons/2.0/JerisLink/platform/macos/"
                 "AppIcon.appiconset/icon_512x512@2x.png")
ASSETS = HERE / "Assets"
SOURCES = HERE / "Assets.sources.txt"

SCALES = (100, 125, 150, 200, 400)
TARGET_SIZES = (16, 24, 32, 48, 256)


def scaled(n, scale):
    return int(n * scale / 100 + 0.5)


def plan():
    """(file name, width, height) for every asset in the package."""
    out = []
    for s in SCALES:
        out.append((f"Square44x44Logo.scale-{s}.png", scaled(44, s), scaled(44, s)))
        out.append((f"Square150x150Logo.scale-{s}.png", scaled(150, s), scaled(150, s)))
        out.append((f"Wide310x150Logo.scale-{s}.png", scaled(310, s), scaled(150, s)))
        out.append((f"StoreLogo.scale-{s}.png", scaled(50, s), scaled(50, s)))
    for t in TARGET_SIZES:
        out.append((f"Square44x44Logo.targetsize-{t}.png", t, t))
        out.append((f"Square44x44Logo.targetsize-{t}_altform-unplated.png", t, t))
    return out


def load_master():
    data = MASTER.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != MASTER_SHA256:
        sys.exit(f"{MASTER.name}: sha256 {digest} is not the pinned v2.0 master {MASTER_SHA256}")
    im = Image.open(io.BytesIO(data))
    im.load()
    if im.mode != "RGBA" or im.size != (1024, 1024):
        sys.exit(f"{MASTER.name}: expected 1024x1024 RGBA, got {im.size} {im.mode}")
    return im


def render(master, w, h):
    side = min(w, h)
    # Resize premultiplied so the transparent corners do not bleed dark fringes.
    tile = master.convert("RGBa").resize((side, side), Image.LANCZOS, reducing_gap=None).convert("RGBA")
    # Lanczos rings a little outside the tile (alpha 1-3 at 16 px); keep the
    # corners truly transparent like the hand-made v2.0 small PNGs.
    tile.putalpha(tile.getchannel("A").point(lambda v: 0 if v < 4 else v))
    canvas = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    canvas.paste(tile, ((w - side) // 2, (h - side) // 2))
    return canvas


def check_shape(name, im):
    w, h = im.size
    side = min(w, h)
    x0 = (w - side) // 2
    alpha = im.getchannel("A")
    # The rounded tile must leave its outer corners transparent.
    for x, y in ((x0, 0), (x0 + side - 1, 0), (x0, side - 1), (x0 + side - 1, side - 1)):
        if alpha.getpixel((x, y)) != 0:
            return f"{name}: corner ({x},{y}) is not transparent"
    if alpha.getpixel((w // 2, h // 2)) != 255:
        return f"{name}: centre of the tile is not opaque"
    return None


def generate():
    master = load_master()
    ASSETS.mkdir(exist_ok=True)
    for old in ASSETS.glob("*.png"):
        old.unlink()
    lines = [
        "# MSIX assets generated by gen-assets.py from the JerisLink v2.0 icon. Do not edit by hand.",
        f"# source: icon-src/{MASTER.name} (copy of {MASTER_ORIGIN})",
        f"# source sha256: {MASTER_SHA256}",
        "# file  WxH  source",
    ]
    for name, w, h in plan():
        im = render(master, w, h)
        err = check_shape(name, im)
        if err:
            sys.exit(err)
        im.save(ASSETS / name, optimize=True)
        lines.append(f"{name}  {w}x{h}  {MASTER.name}")
    SOURCES.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(plan())} assets")


def check():
    master = load_master()
    errors = []
    expected = {name: (w, h) for name, w, h in plan()}
    present = {p.name for p in ASSETS.glob("*")}
    for extra in sorted(present - set(expected)):
        errors.append(f"unexpected file in Assets/: {extra}")
    for name, (w, h) in expected.items():
        path = ASSETS / name
        if not path.exists():
            errors.append(f"missing {name}")
            continue
        got = Image.open(path)
        got.load()
        if got.size != (w, h) or got.mode != "RGBA":
            errors.append(f"{name}: {got.size} {got.mode}, want ({w}, {h}) RGBA")
            continue
        want = render(master, w, h)
        # Compare decoded pixels (PNG bytes vary with zlib); allow 1 step of rounding.
        diff = max(hi for _, hi in ImageChops.difference(got, want).getextrema())
        if diff > 1:
            errors.append(f"{name}: differs from the v2.0 render (max channel diff {diff})")
        err = check_shape(name, got)
        if err:
            errors.append(err)
    if SOURCES.read_text(encoding="utf-8").count(MASTER_SHA256) != 1:
        errors.append(f"{SOURCES.name} does not record the pinned master sha256")
    if errors:
        print("\n".join(errors))
        sys.exit(f"{len(errors)} MSIX asset problem(s); run gen-assets.py generate")
    print(f"OK: {len(expected)} assets match the v2.0 master {MASTER_SHA256[:12]}")


if __name__ == "__main__":
    {"generate": generate, "check": check}.get(sys.argv[1] if len(sys.argv) > 1 else "", lambda: sys.exit(__doc__))()
