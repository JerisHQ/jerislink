#!/usr/bin/env python3
"""Writes auth_vectors.json: connection password test vectors (v0.4.0).

An independent implementation of the JerisLink AUTH maths, so the Swift
host and the Windows viewer are both checked against something neither of
them produced. Passwords here are test strings only. Run:
    python3 gen_auth_vectors.py > auth_vectors.json
"""
import hashlib
import hmac
import json
import struct
import unicodedata

CHANNELS = {"control": 1, "clipboard": 2, "file": 3, "ping": 4}


def h(key, *parts):
    m = hmac.new(key, digestmod=hashlib.sha256)
    for p in parts:
        m.update(p)
    return m.digest()


def seq(n, start):
    return bytes((start + i) & 0xFF for i in range(n))


def vector(name, password, salt, iterations, hn, cn, channel, host_id, session_id, v2h_packet, h2v_packet):
    pw = unicodedata.normalize("NFC", password).encode("utf-8")
    key = hashlib.pbkdf2_hmac("sha256", pw, salt, iterations, 32)
    chan = bytes([CHANNELS[channel]])
    mac_c = h(key, b"jl-c", hn, cn, chan, host_id)
    mac_h = h(key, b"jl-h", hn, cn, chan)
    ks = h(key, b"jl-udp", hn, cn, session_id)
    return {
        "name": name,
        "password": password,
        "password_nfc_utf8": pw.hex(),
        "salt": salt.hex(),
        "iterations": iterations,
        "key": key.hex(),
        "host_nonce": hn.hex(),
        "client_nonce": cn.hex(),
        "channel": channel,
        "host_id": host_id.hex(),
        "mac_c": mac_c.hex(),
        "mac_h": mac_h.hex(),
        "session_id": session_id.hex(),
        "session_key": ks.hex(),
        "udp_v2h_packet": v2h_packet.hex(),
        "udp_v2h_tag": h(ks, b"v2h", v2h_packet)[:8].hex(),
        "udp_h2v_packet": h2v_packet.hex(),
        "udp_h2v_tag": h(ks, b"h2v", h2v_packet)[:8].hex(),
        "challenge_payload": (hn + salt + struct.pack(">I", iterations) + b"\x01" + host_id).hex(),
        "response_payload": (cn + mac_c).hex(),
        "result_ok_payload": (b"\x00" + mac_h + session_id).hex(),
    }


def main():
    vectors = [
        vector("ascii control", "Correct-Horse.42", seq(16, 0x10), 600000, seq(32, 0x40), seq(32, 0x80),
               "control", seq(16, 0xC0), seq(8, 0x01), b"MRM1\x01\x24" + seq(10, 0x20), b"MRM1\x01\x00" + seq(24, 0x30)),
        # Decomposed e + U+0301: NFC must turn it into U+00E9 before UTF-8.
        vector("nfc clipboard", "Café-Pass!x", seq(16, 0xA0), 600000, seq(32, 0x11), seq(32, 0x22),
               "clipboard", seq(16, 0x33), seq(8, 0x44), b"MRM1\x01\x43" + seq(4, 0x55), b"MRM1\x01\x00" + seq(12, 0x66)),
        vector("file channel", "Zz~ten-chars", seq(16, 0x05), 600000, seq(32, 0xF0), seq(32, 0x0F),
               "file", seq(16, 0x77), seq(8, 0x88), b"MRM1\x01\x45" + seq(6, 0x99), b"MRM1\x01\x00" + seq(8, 0xAA)),
    ]
    doc = {
        "about": "JerisLink connection password vectors (design v0.4.0, PR-A). Generated by gen_auth_vectors.py.",
        "kdf": "PBKDF2-HMAC-SHA256 over the UTF-8 of the NFC password, 32-byte key",
        "mac_c": "HMAC-SHA256(K, 'jl-c' | host_nonce | client_nonce | channel(1) | host_id)",
        "mac_h": "HMAC-SHA256(K, 'jl-h' | host_nonce | client_nonce | channel(1))",
        "session_key": "HMAC-SHA256(K, 'jl-udp' | host_nonce | client_nonce | session_id(8))",
        "udp_tag": "first 8 bytes of HMAC-SHA256(session_key, 'v2h' or 'h2v' | packet without tag)",
        "channels": CHANNELS,
        "wire": "MRC1 0x05 AUTH_CHALLENGE host_nonce(32) salt(16) iter(u32 BE) kdf_id(1)=1 host_id(16); "
                "0x03 AUTH_RESPONSE client_nonce(32) mac_c(32); "
                "0x04 AUTH_RESULT status(1): 0 ok + mac_h(32) session_id(8), 1 fail + tries_left(1), "
                "2 locked + retry_s(u32 BE), 3 blocked, 4 auth_required, 5 open_ip_only",
        "vectors": vectors,
    }
    print(json.dumps(doc, indent=2, ensure_ascii=True))


if __name__ == "__main__":
    main()
